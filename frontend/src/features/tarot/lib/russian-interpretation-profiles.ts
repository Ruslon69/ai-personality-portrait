export type RussianTarotInterpretationProfile = {
  action: string;
  reversed: string;
  upright: string;
};

const profile = (
  upright: string,
  reversed: string,
  action: string,
): RussianTarotInterpretationProfile => {
  const sentence = (value: string) => {
    const trimmed = value.trim();
    const capitalized = `${trimmed.charAt(0).toLocaleUpperCase('ru-RU')}${trimmed.slice(1)}`;
    return /[.!?]$/u.test(capitalized) ? capitalized : `${capitalized}.`;
  };
  const actionSentence = (value: string) => {
    const trimmed = value.trim();
    return sentence(/^[а-яё]/u.test(trimmed) ? `Попробуйте ${trimmed}` : trimmed);
  };
  return {
    action: actionSentence(action),
    reversed: sentence(reversed),
    upright: sentence(upright),
  };
};

